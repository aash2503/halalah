export function pi(name, size = 24){
  let o = '';
  IC[name].split(',').forEach((row, y) => [...row].forEach((c, x) => {
    if(c === '1') o += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
  }));
  return `<svg class="pi" width="${size}" height="${size}" viewBox="0 0 8 8" aria-hidden="true">${o}</svg>`;
}
